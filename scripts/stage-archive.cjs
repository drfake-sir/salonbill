// Stage a clean source tree for archiving: everything except the paths that
// .gitignore excludes (deps, build output, wrangler local state, logs).
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const STAGE = process.argv[2];
if (!STAGE) {
  console.error("usage: node scripts/stage-archive.cjs <staging-dir>");
  process.exit(1);
}

// Top-level entries never shipped in a source archive.
const EXCLUDE_TOP = new Set([
  "node_modules", // dependencies — reinstable from package.json
  ".output", // nitro build output
  ".tanstack", // framework cache
  ".wrangler", // local D1 / R2 / KV state (contains real local data)
  "dist", // vite build output
  "deploy-worker", // generated by scripts/sync-deploy.cjs
  "deploy-assets", // generated by scripts/sync-deploy.cjs
  ".git",
  ".DS_Store",
]);

// Directory names skipped anywhere in the tree.
const EXCLUDE_ANY = new Set(["node_modules", ".git", ".DS_Store", "__pycache__"]);

const SKIP_EXT = new Set([".log", ".local", ".zip"]);

function shouldSkip(name) {
  if (EXCLUDE_ANY.has(name)) return true;
  if (name.startsWith("npm-debug")) return true;
  if (name.endsWith(".log")) return true;
  return SKIP_EXT.has(path.extname(name));
}

let copied = 0;
let bytes = 0;

function walk(rel) {
  const src = path.join(ROOT, rel);
  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const e of entries) {
    const childRel = rel ? `${rel}/${e.name}` : e.name;
    // Top-level exclusions only apply at the root depth.
    if (!rel && EXCLUDE_TOP.has(e.name)) continue;
    if (shouldSkip(e.name)) continue;

    const dest = path.join(STAGE, childRel);
    const childSrc = path.join(src, e.name);
    if (e.isDirectory()) {
      fs.mkdirSync(dest, { recursive: true });
      walk(childRel);
    } else if (e.isFile()) {
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(childSrc, dest);
      copied++;
      bytes += fs.statSync(dest).size;
    }
  }
}

fs.rmSync(STAGE, { recursive: true, force: true });
fs.mkdirSync(STAGE, { recursive: true });
walk("");

console.log(`staged ${copied} files (${(bytes / 1024).toFixed(0)} KiB) -> ${STAGE}`);
